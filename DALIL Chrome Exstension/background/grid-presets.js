/**
 * دالة توليد مربعات الشبكة لأي نوع من الإعدادات
 */
function getCellsForPreset(presetKey, customConfig = {}) {
  // 1. إذا تم تمرير شبكة مجهزة مسبقاً (من رفع ملف KML أو رسم مباشر)
  if (customConfig && Array.isArray(customConfig.customCells) && customConfig.customCells.length > 0) {
    return customConfig.customCells;
  }

  // 2. إذا تم تمرير حدود مخصصة Bounding Box (سواء بالرسم أو من ملف أو إحداثيات مخصصة)
  if (presetKey === "custom" || customConfig.customBounds) {
    const bounds = customConfig.customBounds || { minLat: 22.0, maxLat: 31.80, minLng: 24.80, maxLng: 36.90 };
    const rows = parseInt(customConfig.gridRows) || 12;
    const cols = parseInt(customConfig.gridCols) || 12;
    const overlapPercent = customConfig.overlapPercent !== undefined ? customConfig.overlapPercent : 0.05;

    return generateSeamlessMeshCells({
      bounds,
      rows,
      cols,
      overlapPercent
    }, customConfig.filterPolygon);
  }

  const preset = GRID_PRESETS[presetKey] || GRID_PRESETS.egypt_full_country;

  if (preset.type === "mesh") {
    const rows = parseInt(customConfig.gridRows) || preset.rows || 18;
    const cols = parseInt(customConfig.gridCols) || preset.cols || 22;
    return generateSeamlessMeshCells({
      ...preset,
      rows,
      cols
    }, customConfig.filterPolygon);
  }

  if (preset.type === "clusters") {
    const delta = preset.delta || 0.065;
    return preset.clusters.map((c, index) => ({
      id: `cell_${index + 1}`,
      index,
      name: c.name,
      centerLat: c.lat,
      centerLng: c.lng,
      bounds: {
        minLat: Number((c.lat - delta).toFixed(6)),
        maxLat: Number((c.lat + delta).toFixed(6)),
        minLng: Number((c.lng - delta).toFixed(6)),
        maxLng: Number((c.lng + delta).toFixed(6))
      },
      status: "pending",
      itemsFound: 0
    }));
  }

  return [];
}

/**
 * توليد شبكة متصلة هندسياً بدون أي فواصل نهائياً (Seamless Mesh)
 * كل مربع يشترك مع المربع المجاور له في نفس الحد الهندسي بالمليمتر
 */
function generateSeamlessMeshCells(preset, filterPolygon = null) {
  const { bounds, rows, cols, overlapPercent } = preset;
  const cells = [];
  const baseLatStep = (bounds.maxLat - bounds.minLat) / rows;
  const baseLngStep = (bounds.maxLng - bounds.minLng) / cols;
  const overlap = overlapPercent || 0.05;

  let counter = 0;
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const minLatRaw = bounds.minLat + r * baseLatStep;
      const maxLatRaw = minLatRaw + baseLatStep;
      const minLngRaw = bounds.minLng + c * baseLngStep;
      const maxLngRaw = minLngRaw + baseLngStep;

      // تداخل بسيط لمنع ضياع أي منشأة تقع على الحدود تماماً
      const latExtra = baseLatStep * overlap;
      const lngExtra = baseLngStep * overlap;

      const minLat = Number(Math.max(bounds.minLat, minLatRaw - latExtra).toFixed(6));
      const maxLat = Number(Math.min(bounds.maxLat, maxLatRaw + latExtra).toFixed(6));
      const minLng = Number(Math.max(bounds.minLng, minLngRaw - lngExtra).toFixed(6));
      const maxLng = Number(Math.min(bounds.maxLng, maxLngRaw + lngExtra).toFixed(6));

      const centerLat = Number(((minLat + maxLat) / 2).toFixed(6));
      const centerLng = Number(((minLng + maxLng) / 2).toFixed(6));

      // فحص التقاطع مع مضلع منطقة الدراسة إن وُجد
      if (filterPolygon && typeof SpatialUtils !== "undefined" && typeof SpatialUtils.doesCellIntersectPolygon === "function") {
        const intersects = SpatialUtils.doesCellIntersectPolygon(
          { bounds: { minLat, maxLat, minLng, maxLng }, centerLat, centerLng },
          filterPolygon
        );
        if (!intersects) {
          continue;
        }
      }

      let regionDesc = "";
      if (centerLat >= 22.0 && centerLat <= 31.8 && centerLng >= 24.8 && centerLng <= 36.9) {
        regionDesc = getEgyptRegionDescription(centerLat, centerLng);
      } else {
        regionDesc = `إحداثيات (${centerLat.toFixed(2)}, ${centerLng.toFixed(2)})`;
      }
      const cellName = `مربع (${r + 1}, ${c + 1}): ${regionDesc}`;

      cells.push({
        id: `mesh_cell_${counter + 1}`,
        index: counter,
        name: cellName,
        regionDesc,
        centerLat,
        centerLng,
        bounds: { minLat, maxLat, minLng, maxLng },
        status: "pending",
        itemsFound: 0
      });
      counter++;
    }
  }
  return cells;
}

function generateBBoxGridCells(bounds, rows, cols) {
  const cells = [];
  const latStep = (bounds.maxLat - bounds.minLat) / rows;
  const lngStep = (bounds.maxLng - bounds.minLng) / cols;
  let counter = 0;

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const minLat = bounds.minLat + r * latStep;
      const maxLat = minLat + latStep;
      const minLng = bounds.minLng + c * lngStep;
      const maxLng = minLng + lngStep;
      const centerLat = Number((minLat + latStep / 2).toFixed(6));
      const centerLng = Number((minLng + lngStep / 2).toFixed(6));
      const regionDesc = getEgyptRegionDescription(centerLat, centerLng);

      cells.push({
        id: `cell_${counter + 1}`,
        index: counter,
        name: `مربع (${r + 1}, ${c + 1}): ${regionDesc}`,
        regionDesc,
        centerLat,
        centerLng,
        bounds: {
          minLat: Number(minLat.toFixed(6)),
          maxLat: Number(maxLat.toFixed(6)),
          minLng: Number(minLng.toFixed(6)),
          maxLng: Number(maxLng.toFixed(6))
        },
        status: "pending",
        itemsFound: 0
      });
      counter++;
    }
  }
  return cells;
}

